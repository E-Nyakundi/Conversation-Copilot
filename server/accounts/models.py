import binascii
import os
import uuid

from django.contrib.auth.base_user import BaseUserManager
from django.contrib.auth.models import AbstractUser
from django.db import models
from django.utils import timezone


class UserManager(BaseUserManager):
    """
    Custom manager because AbstractUser's default expects username-first
    creation; this app is invite-only and email-first, so `create_user`/
    `create_superuser` take email as the primary identifier instead.
    """

    use_in_migrations = True

    def _create_user(self, email, password, **extra_fields):
        if not email:
            raise ValueError("Users must have an email address")
        email = self.normalize_email(email)
        # username is kept (AbstractUser requires it) but unused for login;
        # default it to the email so it's still unique and non-blank.
        extra_fields.setdefault("username", email)
        user = self.model(email=email, **extra_fields)
        user.set_password(password)
        user.save(using=self._db)
        return user

    def create_user(self, email, password=None, **extra_fields):
        extra_fields.setdefault("is_staff", False)
        extra_fields.setdefault("is_superuser", False)
        return self._create_user(email, password, **extra_fields)

    def create_superuser(self, email, password=None, **extra_fields):
        extra_fields.setdefault("is_staff", True)
        extra_fields.setdefault("is_superuser", True)
        return self._create_user(email, password, **extra_fields)


class User(AbstractUser):
    """
    Custom user model, introduced alongside multi-tenancy (2026-08-30).

    Deliberately a custom model rather than reusing django.contrib.auth's
    default User: this app is invite-only (owner creates every account,
    see accounts/services.py:invite_user) and email is the real login
    identifier, not username. Swapping AUTH_USER_MODEL after the first
    real migration is painful (it's an FK target from every tenant-scoped
    model), so this is done now, before any tenant data exists, rather
    than deferred.
    """

    email = models.EmailField(unique=True)

    # Invite-flow support: an admin-created account gets a random temp
    # password and must change it before getting a normal-lifetime
    # session. Cleared once the user sets their own password.
    must_change_password = models.BooleanField(default=True)

    created_by = models.ForeignKey(
        "self",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="invited_users",
    )

    created_at = models.DateTimeField(auto_now_add=True)

    objects = UserManager()

    USERNAME_FIELD = "email"
    REQUIRED_FIELDS = []  # username still exists on AbstractUser but isn't required for createsuperuser prompts

    def __str__(self):
        return self.email


def _generate_token_key() -> str:
    # 40 hex chars (20 random bytes) — same length/shape as DRF's token
    # scheme, generated by hand here since this project doesn't otherwise
    # depend on djangorestframework.
    return binascii.hexlify(os.urandom(20)).decode()


class AuthToken(models.Model):
    """
    Hand-rolled bearer token, not django.contrib.sessions cookies.

    Chosen because the same credential has to work for two very different
    transports: a REST `Authorization: Bearer <token>` header from
    Flutter's http client, AND a WebSocket handshake
    (wss://host/ws/audio/?token=<token>) where there's no standard place
    to put a cookie from a mobile client. One opaque token satisfies both
    without needing cookie-jar plumbing on the Flutter side.

    One token per user at a time (OneToOneField) rather than a table of
    many tokens per user — this app has no concept of "log out on this
    device only" yet; issuing a new token invalidates the old one, which
    is also how you'd forcibly kick a device if needed (rotate, don't
    just deactivate).
    """

    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name="auth_token")
    key = models.CharField(max_length=40, unique=True, default=_generate_token_key)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Token for {self.user.email}"

    @classmethod
    def issue_for(cls, user: "User") -> "AuthToken":
        """Replace any existing token for this user with a fresh one."""
        cls.objects.filter(user=user).delete()
        return cls.objects.create(user=user, key=_generate_token_key())


class TenantQuota(models.Model):
    """
    Per-tenant usage cap.

    Session-cap fix (2026-09-01): the account-wide *minutes* pool
    (`max_minutes`/`minutes_used`, a lifetime/cumulative cap across all
    sessions) has been removed outright — it was a design mistake per
    Lewis, not just a bug. Session time is now capped per-session (a
    flat, resetting clock — see conversation.models.Session's
    SESSION_HARD_CAP_MINUTES and audio/consumers.py's periodic check),
    not accumulated against this model at all.

    `max_sessions`/`sessions_used` (the session-*count* cap) is
    unchanged — still the only numeric cap this model tracks.

    `is_active` is a separate on/off switch from the numeric cap —
    revoking access shouldn't require zeroing out (and losing) a user's
    configured quota number.
    """

    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name="quota")

    max_sessions = models.PositiveIntegerField(null=True, blank=True)
    sessions_used = models.PositiveIntegerField(default=0)

    is_active = models.BooleanField(default=True)

    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Quota for {self.user.email}"

    def sessions_remaining(self):
        if self.max_sessions is None:
            return None
        return max(0, self.max_sessions - self.sessions_used)

    def sessions_exhausted(self) -> bool:
        return self.max_sessions is not None and self.sessions_used >= self.max_sessions

    def can_start_session(self) -> tuple[bool, str | None]:
        """
        Returns (allowed, reason). reason is None when allowed=True, else
        one of "account_inactive" / "sessions_exhausted" — kept as
        stable string codes so callers (REST view, WS consumer,
        eventually the Flutter client) can branch on the reason rather
        than parsing a human sentence.

        Session-cap fix (2026-09-01): "minutes_exhausted" is gone along
        with the minutes pool it referred to — per-session time is now
        enforced by a hard 2-hour ceiling on the session itself (see
        Session.is_past_hard_cap), not by anything checked here at
        session-start time.
        """
        if not self.is_active:
            return False, "account_inactive"
        if self.sessions_exhausted():
            return False, "sessions_exhausted"
        return True, None

    def register_usage(self, *, minutes: float, session=None, note: str = ""):
        """
        Record consumption of one completed session: bump the session
        counter and write an audit row. Called once, at session end,
        from conversation/usage.py:finalize_session_usage — never from
        the WS consumer directly, so REST-triggered ends
        (session_end_view) and WS-triggered ends both go through the
        same accounting path.

        Session-cap fix (2026-09-01): `minutes` is still accepted (and
        still recorded on the UsageEvent audit row below, for the admin
        usage timeline) but no longer summed into any cap on this model
        — there is no minutes pool left to add it to.
        """
        self.sessions_used = models.F("sessions_used") + 1
        self.save(update_fields=["sessions_used", "updated_at"])
        self.refresh_from_db(fields=["sessions_used"])
        UsageEvent.objects.create(user=self.user, session=session, minutes=minutes, note=note)

    def adjust(self, *, sessions_delta: int = 0, note: str = ""):
        """
        Admin-panel entry point for "+N sessions" (or negative to claw
        back). Adjusts the *max*, not *used* — adding quota should mean
        "you can now do more," not silently rewinding usage history.
        Logged as a UsageEvent with session=None so the admin UI's usage
        timeline shows manual grants alongside real consumption.
        """
        if sessions_delta:
            self.max_sessions = max(0, (self.max_sessions or 0) + sessions_delta)
        self.save(update_fields=["max_sessions", "updated_at"])
        if sessions_delta:
            UsageEvent.objects.create(
                user=self.user,
                session=None,
                minutes=0,
                note=note or f"admin adjustment: sessions{sessions_delta:+d}",
            )


class UsageEvent(models.Model):
    """
    Audit trail row: either real consumption (session set, minutes > 0)
    or an admin's manual quota adjustment (session=None). Exists so the
    admin UI can show *why* a user is at, say, 8/10 sessions instead of
    just the bare number — see TenantQuota.register_usage/.adjust, the
    only two places that create these.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="usage_events")
    session = models.ForeignKey(
        "conversation.Session", on_delete=models.SET_NULL, null=True, blank=True
    )
    minutes = models.FloatField(default=0)
    note = models.CharField(max_length=255, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.user.email}: {self.minutes:.1f}min ({self.created_at:%Y-%m-%d %H:%M})"
